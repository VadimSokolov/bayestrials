test_that("toxicity boundary and OC", {
  b <- tox_bayes_boundary()
  expect_equal(b$stop_at, c(3, 4, 5, 6, 7, 8, 9, 11))
  oc <- tox_oc(b)
  expect_lt(max(abs(oc$p_stop - c(0.03, 0.15, 0.39, 0.84, 0.99))), 0.011)
  expect_equal(round(oc$expected_n, 1), c(39.1, 36.5, 31.5, 19.8, 12.2), tolerance = 0.3)
  pk <- tox_pocock_boundary()
  expect_lte(pk$alpha_achieved, oc$p_stop[3] + 1e-9)
})
