test_that("GPS fit runs", {
  set.seed(1); E <- runif(400, 0.2, 5)
  lam <- ifelse(runif(400) < 0.3, rgamma(400, 2, 1), rgamma(400, 2, 4))
  f <- safety_gps_fit(rpois(400, lam * E), E)
  expect_true(all(is.finite(f$par)))
})
