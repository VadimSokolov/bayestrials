test_that("survival workbook tables match the zip", {
  t <- surv_events_table()
  expect_equal(round(t$se, 3), c(0.200, 0.141, 0.100, 0.071))
  expect_equal(round(t$p_benefit, 2), c(0.87, 0.94, 0.99, 1.00))
  expect_equal(round(t$p_mcid, 2), c(0.72, 0.80, 0.88, 0.95))
  expect_equal(surv_events_table(prior_sd = 0.2)$prior_events, rep(100, 4))
  x <- surv_pp_cp(c(300, 300, 300, 450), c(0.75, 0.85, 0.95, 0.88))
  expect_equal(round(x$z, 2), c(2.49, 1.41, 0.44, 1.36))
  expect_equal(round(x$pp, 2), c(0.94, 0.51, 0.09, 0.25))
  expect_equal(round(x$cp_design, 2), c(0.95, 0.72, 0.35, 0.42))
  expect_equal(round(x$cp_trend, 2), c(0.99, 0.52, 0.03, 0.22))
  expect_equal(round(surv_pp_cp(300, 0.85, Dmax = 900)$pp, 2), 0.63)
  g <- surv_gamma_hazard(60, 400)
  expect_equal(unname(round(g$hazard, 3)), c(0.150, 0.114, 0.190), tolerance = 0.002)
  expect_equal(unname(round(g$median[2:3], 1)), c(3.6, 6.1), tolerance = 0.06)
})

test_that("RMST closed form agrees with numerical integration; NPH scenarios ordered", {
  S <- function(t) surv_pwexp_S(t, c(0.15, 0.09), c(0, 1))
  expect_equal(surv_rmst(5, c(0.15, 0.09), c(0, 1)), stats::integrate(S, 0, 5)$value, tolerance = 1e-6)
  expect_equal(surv_rmst(5, 0.15), (1 - exp(-0.75)) / 0.15)
  e <- surv_nph_example()
  expect_true(e$rmst_diff[2] < e$rmst_diff[1])
  expect_equal(e$cumhaz_ratio[1], 0.6)
  expect_equal(surv_rmst(5, 0.15, cure = 0.2), 0.2 * 5 + 0.8 * surv_rmst(5, 0.15))
})

