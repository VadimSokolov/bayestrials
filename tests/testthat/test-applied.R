test_that("monitoring look table matches the zip and calibration controls the null", {
  m <- monitor_three_rulebooks()
  expect_equal(round(m$obf_bound, 2), c(4.05, 2.86, 2.34, 2.02))
  expect_equal(round(m$z, 2), c(2.15, 2.28, 2.62, 2.81))
  expect_equal(round(m$flat_p, 3), c(0.984, 0.989, 0.996, 0.998), tolerance = 0.0011)
  expect_equal(round(m$flat_p_mcid, 2), c(0.89, 0.84, 0.85, 0.84))
  expect_equal(round(m$skep_p, 3), c(0.92, 0.96, 0.985, 0.993), tolerance = 0.0011)
  expect_equal(round(m$skep_p_mcid, 2), c(0.51, 0.54, 0.61, 0.63))
  expect_equal(round(m$bf, 1), c(2.8, 3.5, 6.9, 10.7))
  expect_equal(m$obf_stop, c(FALSE, FALSE, TRUE, TRUE))
  expect_false(any(m$bf_stop))
  expect_equal(round(m$skep_mean_hr[3], 3), 0.886)
  cal <- attr(m, "calibration")
  expect_equal(gs_crossing_prob(cal$bounds, c(0.25, 0.5, 0.75, 1))$total, 0.025, tolerance = 1e-6)
  # the zip's uncalibrated 0.99 skeptical rule is conservative; the calibrated threshold is lower
  expect_true(cal$threshold < 0.99)
  expect_equal(monitor_harm_rule(600, 0.83, Dmax = 1200, z_crit = 2.02)$pp_success, 0.89, tolerance = 0.006)
  expect_equal(monitor_harm_rule(60, 1.3)$trigger_hr, 1.2)
})

test_that("reanalysis tables match the zip and Brophy-Joseph", {
  g <- reanalysis_gusto()
  # arm model reproduces Brophy and Joseph (1995) Table 2: 0.9995, 0.98, 0.44, 0.17; 0.48 at w = 0
  expect_equal(g$arm_p_benefit, c(0.9995, 0.98, 0.44, 0.17), tolerance = 0.01)
  expect_equal(g$arm_p_mcid[1], 0.49, tolerance = 0.015)
  expect_equal(round(g$p_benefit, 3), c(1.000, 0.999, 0.992, 0.968), tolerance = 0.0006)
  expect_equal(round(g$p_mcid, 2), c(0.50, 0.33, 0.03, 0.00))
  e <- reanalysis_eolia()
  expect_equal(round(e$post_ratio, 2), c(0.78, 0.83, 0.89, 0.75), tolerance = 0.011)
  expect_equal(round(e$p_benefit, 2), c(0.95, 0.91, 0.87, 0.99))
  expect_equal(round(e$p_0.8, 2), c(0.57, 0.37, 0.17, 0.70))
  a <- reanalysis_andromeda()
  expect_equal(round(a$post_ratio, 2), c(0.75, 0.79, 0.87, 0.92, 0.77))
  expect_equal(round(a$p_benefit, 2), c(0.97, 0.95, 0.90, 0.79, 0.98))
  expect_equal(round(a$p_0.8, 2), c(0.66, 0.54, 0.21, 0.10, 0.63), tolerance = 0.011)
  r <- reanalysis_recovery()
  expect_equal(round(r$shrunk_rr, 2), c(0.66, 0.82, 1.13))
  expect_equal(round(r$p_benefit, 2), c(1.00, 1.00, 0.19))
  expect_equal(round(r$p_benefit[3], 2), 0.19)
})
